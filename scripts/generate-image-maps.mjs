#!/usr/bin/env node
// Writes the two image registries from assets/images (React Native needs a static require() for every bundled picture):
//   src/utils/images.ts        the app's own pictures, the files directly in assets/images, keyed by name (".png" left off)
//   src/utils/lessonImages.ts  the lesson pictures, every file in its subfolders, keyed by the path the content names
// It also lists byte-identical files, which should be one file the content points at instead.
// Usage: node scripts/generate-image-maps.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = join(root, 'assets/images');
const IMAGE = /\.(png|jpe?g|webp|gif)$/i;

const walk = (dir) => readdirSync(dir).sort().flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : IMAGE.test(n) ? [p] : [];
});
const all = walk(imagesDir);
const own = all.filter((p) => dirname(p) === imagesDir);
const lesson = all.filter((p) => dirname(p) !== imagesDir);
const rel = (p) => relative(root, p).split('\\').join('/');

const appMap = own.map((p) => {
  const file = rel(p).slice('assets/images/'.length);
  return `  "${file.replace(/\.png$/, '')}": require('../../${rel(p)}'),`;
});
writeFileSync(join(root, 'src/utils/images.ts'), `// Generated by scripts/generate-image-maps.mjs from assets/images. React Native needs a static require() for every bundled picture.
export const IMAGES: Record<string, number> = {
${appMap.join('\n')}
};
`);

const lessonMap = lesson.map((p) => `  '${rel(p)}': require('../../${rel(p)}'),`);
writeFileSync(join(root, 'src/utils/lessonImages.ts'), `// Generated by scripts/generate-image-maps.mjs: every lesson picture in assets/images/*/, keyed by the path the content names.
export const LESSON_IMAGES: Record<string, number> = {
${lessonMap.join('\n')}
};

/** The bundled image for a content path, or undefined when the path isn't registered (the picture then draws without it). */
export const lessonImage = (path?: string) => (path ? LESSON_IMAGES[path] : undefined);
`);

const byHash = new Map();
for (const p of all) {
  const h = createHash('md5').update(readFileSync(p)).digest('hex');
  byHash.set(h, [...(byHash.get(h) ?? []), rel(p)]);
}
const copies = [...byHash.values()].filter((g) => g.length > 1);
console.log(`images.ts: ${own.length} images; lessonImages.ts: ${lesson.length} images.`);
if (copies.length) {
  console.log(`${copies.length} groups of byte-identical files (keep one, point the content at it, delete the rest):`);
  for (const g of copies) console.log(`  ${g.join(', ')}`);
}
